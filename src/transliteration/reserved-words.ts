// Латинське імʼя не має збігатися з ключовим словом чи глобальним обʼєктом: інакше змінна «Сет»
// затінила б Set, у який перекладається «Фракція».
export function collectReservedWords(globalObject: object): ReadonlySet<string> {
  return new Set([...JAVASCRIPT_RESERVED_WORDS, ...Object.getOwnPropertyNames(globalObject)]);
}
